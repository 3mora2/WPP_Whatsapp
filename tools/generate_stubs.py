"""Generate complete composed service stubs from the runtime registry. No browser I/O."""

from __future__ import annotations

import argparse
import ast
import inspect
import subprocess
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from WPP_Whatsapp.core.service_registry import service_definitions  # noqa: E402
from WPP_Whatsapp.core.services import MessagesService, ServiceHub  # noqa: E402

TARGET = ROOT / "WPP_Whatsapp/core/service_types.pyi"
HELPERS = (
    "send_text",
    "get_message",
    "reconcile",
    "recover",
    "search",
    "send_media",
    "download_media_to",
    "delivery_status",
    "wait_for_delivery",
)


def generated():
    lines = [
        '"""Generated by tools/generate_stubs.py; do not edit."""',
        "from typing import Any, Callable, Dict, List, Optional, Sequence",
        "from WPP_Whatsapp.api.model import (BusinessProfileOptions, ChatListOptions, CollectionOptions, CommunityOptions, GroupDescriptionOptions, GroupIconOptions, GroupPropertyOptions, GroupSubjectOptions, NewsletterOptions, OrderItem, OrderMessageOptions, PollOptions, ProductOptions, SendTextOptions)",
        "from .acknowledgements import Acknowledgement, AckTarget",
        "from .contracts import Callback",
        "from .delivery import DeliveryReceipt, DeliveryTracker",
        "from .media import Progress",
        "from .models import Chat, Group, GroupMember, Message, TypedServices",
        "from .services import EventsService",
        "",
    ]
    hub = ServiceHub(SimpleNamespace())
    for sync in (False, True):
        prefix = "Sync" if sync else "Async"
        for definition in service_definitions():
            service = getattr(hub, definition.name)
            methods = dict(definition.operations())
            if definition.name == "messages":
                methods.update({name: getattr(service, name) for name in HELPERS})
            lines.append(f"class {prefix}{definition.name.title()}:")
            if definition.name == "messages":
                lines.append("    deliveries: DeliveryTracker")
            for name in sorted(methods):
                signature = inspect.signature(getattr(service, name))
                parameters = [inspect.Parameter("self", inspect.Parameter.POSITIONAL_OR_KEYWORD)]
                parameters += [
                    parameter.replace(
                        annotation=parameter.annotation
                        if parameter.annotation is not inspect.Parameter.empty
                        else Any,
                        default=Ellipsis
                        if parameter.default is not inspect.Parameter.empty
                        else inspect.Parameter.empty,
                    )
                    for parameter in signature.parameters.values()
                ]
                result = signature.return_annotation
                if result is inspect.Signature.empty:
                    result = (
                        "DeliveryReceipt"
                        if definition.name == "messages" and MessagesService._tracked(name)
                        else Any
                    )
                value = (
                    str(signature.replace(parameters=parameters, return_annotation=result))
                    .replace("typing.", "")
                    .replace("WPP_Whatsapp.api.model.", "")
                    .replace("Ellipsis", "...")
                )
                lines.append(f"    {'' if sync else 'async '}def {name}{value}: ...")
            lines.append("")
        if sync:
            lines.append("class SyncTypedServices:")
            for name in (
                "get_message",
                "get_messages",
                "list_chats",
                "get_group",
                "get_group_members",
            ):
                signature = inspect.signature(getattr(hub.typed, name))
                parameters = [inspect.Parameter("self", inspect.Parameter.POSITIONAL_OR_KEYWORD)]
                parameters += [
                    parameter.replace(default=Ellipsis)
                    if parameter.default is not inspect.Parameter.empty
                    else parameter
                    for parameter in signature.parameters.values()
                ]
                value = str(signature.replace(parameters=parameters)).replace("Ellipsis", "...")
                lines.append(f"    def {name}{value}: ...")
            lines.append("")
        lines.append(f"class {prefix}Services:")
        lines += [
            f"    {definition.name}: {prefix}{definition.name.title()}"
            for definition in service_definitions()
        ]
        lines += [
            "    events: EventsService",
            "    typed: TypedServices" if not sync else "    typed: SyncTypedServices",
            "",
        ]
    value = "\n".join(lines)
    ast.parse(value)
    normalized = subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "--stdin-filename", str(TARGET), "-"],
        input=value,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(TARGET), "-"],
        input=normalized,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    value = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != value:
            raise SystemExit("Service stubs are stale; run python tools/generate_stubs.py")
    else:
        TARGET.write_text(value, encoding="utf-8")
    print("Validated generated sync/async service signatures")


if __name__ == "__main__":
    main()
