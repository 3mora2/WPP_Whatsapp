"""Check local guide links, Python recipes and generated service signatures.

Static checks only: never execute a snippet, start a browser or send a message.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import re
import sys
from functools import lru_cache
from pathlib import Path
from types import SimpleNamespace
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# The standalone script also works before an editable install is configured.
from WPP_Whatsapp import AsyncClient, Create, MultiCreate, Whatsapp  # noqa: E402
from WPP_Whatsapp.core.consumers import DurableConsumer  # noqa: E402
from WPP_Whatsapp.core.delivery import DeliveryTracker  # noqa: E402
from WPP_Whatsapp.core.journal import EventJournal  # noqa: E402
from WPP_Whatsapp.core.service_registry import service_definitions  # noqa: E402
from WPP_Whatsapp.core.services import EventsService, MessagesService, ServiceHub  # noqa: E402
from WPP_Whatsapp.core.subscriptions import ClientEvents  # noqa: E402


@lru_cache(maxsize=1)
def service_hub():
    # Binding operations/signatures does not use the context or perform I/O.
    return ServiceHub(SimpleNamespace())


def signature(function):
    value = inspect.signature(function)
    parameters = list(value.parameters.values())
    if parameters and parameters[0].name in ("self", "cls"):
        parameters = parameters[1:]
    return value.replace(parameters=parameters)


def generated_api():
    lines = [
        "# Generated service API",
        "",
        "Generated from the current service registry; do not edit this file by hand.",
        "Run `python tools/verify_docs.py --write-api` after changing the API.",
        "",
        "Signatures omit annotations for readability. Native calls are awaited; sync",
        "composed calls use `client.services`. Corresponding flat async methods are",
        "listed alongside sync names when available. Tracked message sends additionally",
        "accept `operation_id` and `timeout`; flat methods retain raw results. See",
        "[API recipes](API_REFERENCE.md) and [delivery semantics](ARCHITECTURE.md#sending-and-uncertain-results).",
        "",
    ]
    for definition in service_definitions():
        service = getattr(service_hub(), definition.name)
        operations = dict(definition.operations())
        if definition.name == "messages":
            operations.update(
                {
                    name: getattr(MessagesService, name)
                    for name in (
                        "send_text",
                        "get_message",
                        "reconcile",
                        "recover",
                        "search",
                        "send_media",
                        "download_media_to",
                        "delivery_status",
                        "wait_for_delivery",
                    )
                }
            )
        lines += [
            f"## {definition.name}",
            "",
            "| Native service signature | Flat operation(s) |",
            "| --- | --- |",
        ]
        for name, source in sorted(operations.items()):
            bound = signature(getattr(service, name))
            plain = bound.replace(
                return_annotation=inspect.Signature.empty,
                parameters=[
                    p.replace(annotation=inspect.Parameter.empty) for p in bound.parameters.values()
                ],
            )
            flat = []
            candidates = (source.__name__.rstrip("_"), source.__name__)
            for candidate in dict.fromkeys(candidates):
                if hasattr(Whatsapp, candidate):
                    prefix = (
                        "await "
                        if inspect.iscoroutinefunction(getattr(Whatsapp, candidate))
                        else ""
                    )
                    flat.append(f"`{prefix}client.{candidate}`")
            lines.append(
                f"| `{definition.name}.{name}{plain}` | {', '.join(flat) or 'Service helper'} |"
            )
        lines.append("")
    lines += ["## events", "", "| Native event signature | Flat registration |", "| --- | --- |"]
    for name, flat in (
        ("on_message", "onMessage"),
        ("on_any_message", "onAnyMessage"),
        ("on", "Supported event name"),
    ):
        value = signature(getattr(EventsService, name))
        plain = value.replace(
            return_annotation=inspect.Signature.empty,
            parameters=[
                p.replace(annotation=inspect.Parameter.empty) for p in value.parameters.values()
            ],
        )
        lines.append(f"| `events.{name}{plain}` | `{flat}` |")
    lines += [
        "",
        "Event registration is synchronous; callbacks may be sync or async.",
        "The inventory describes the Python surface, not live upstream/account permissions.",
        "",
    ]
    lines += [
        "## typed",
        "",
        "Opt-in dataclass results; raw services keep their original results.",
        "",
    ]
    for name in ("get_message", "get_messages", "list_chats", "get_group", "get_group_members"):
        bound = signature(getattr(service_hub().typed, name))
        plain = bound.replace(
            return_annotation=inspect.Signature.empty,
            parameters=[
                parameter.replace(annotation=inspect.Parameter.empty)
                for parameter in bound.parameters.values()
            ],
        )
        lines.append(f"- `typed.{name}{plain}`")
    lines.append("")
    return "\n".join(lines)


def slug(text):
    text = re.sub(r"<[^>]+>", "", text).strip().lower()
    text = re.sub(r"[^\w\- ]", "", text, flags=re.UNICODE)
    return text.replace(" ", "-")


def link_errors(path, contents):
    errors = []
    for match in re.finditer(r"\[[^\]\n]*\]\(([^)\n]+)\)", contents):
        target = match[1].strip().strip("<>")
        parsed = urlsplit(target)
        prefix = "/3mora2/WPP_Whatsapp/blob/main/"
        repository_link = parsed.netloc == "github.com" and parsed.path.startswith(prefix)
        if repository_link:
            destination = (ROOT / unquote(parsed.path[len(prefix) :])).resolve()
        elif parsed.scheme or parsed.netloc:
            continue
        else:
            destination = (path.parent / unquote(parsed.path)).resolve() if parsed.path else path
        if not destination.exists():
            errors.append(f"{path.name}: missing link {target}")
        elif parsed.fragment and destination.suffix == ".md":
            headings = re.findall(
                r"^#{1,6}\s+(.+?)\s*#*$", destination.read_text(encoding="utf-8"), re.M
            )
            anchors = {slug(heading) for heading in headings}
            if unquote(parsed.fragment) not in anchors:
                errors.append(f"{path.name}: missing heading {target}")
    return errors


def chain(node):
    names = []
    while isinstance(node, ast.Attribute):
        names.append(node.attr)
        node = node.value
    if isinstance(node, ast.Name):
        return [node.id, *reversed(names)]
    return []


def recipe_errors(source, location):
    errors = []
    try:
        compile(source, location, "exec", flags=ast.PyCF_ALLOW_TOP_LEVEL_AWAIT)
        tree = compile(
            source, location, "exec", flags=ast.PyCF_ONLY_AST | ast.PyCF_ALLOW_TOP_LEVEL_AWAIT
        )
    except SyntaxError as error:
        return [f"{location}: invalid Python at line {error.lineno}: {error.msg}"]
    bindings = {
        "Create": Create,
        "AsyncClient": AsyncClient,
        "MultiCreate": MultiCreate,
        "client": Whatsapp,
        "creator": Create,
        "native": AsyncClient,
    }

    def resolve(node):
        names = chain(node)
        if not names:
            return None
        if names[:2] == ["self", "client"]:
            names = ["client", *names[2:]]
        value = bindings.get(names[0])
        for name in names[1:]:
            if value is None:
                return None
            if value in (Whatsapp, AsyncClient) and name in ("services", "async_services"):
                value = service_hub()
            elif value is AsyncClient and name == "typed":
                value = service_hub().typed
            elif value is AsyncClient and name == "events":
                value = ClientEvents
            elif value is AsyncClient and name in (*service_hub().names,):
                value = getattr(service_hub(), name)
            elif isinstance(value, MessagesService) and name == "deliveries":
                value = DeliveryTracker
            else:
                value = getattr(value, name, None)
        return value

    class Visitor(ast.NodeVisitor):
        def visit_AnnAssign(self, node):
            if isinstance(node.target, ast.Name) and isinstance(node.annotation, ast.Name):
                kind = bindings.get(node.annotation.id)
                if kind in (Create, AsyncClient, Whatsapp):
                    bindings[node.target.id] = kind
            self.generic_visit(node)

        def visit_Assign(self, node):
            if isinstance(node.value, ast.Call):
                value = resolve(node.value.func)
                assigned = value if value in (Create, AsyncClient, MultiCreate) else None
                if value is EventJournal.consumer:
                    assigned = DurableConsumer
                if isinstance(node.value.func, ast.Attribute) and node.value.func.attr in (
                    "start",
                    "start_",
                ):
                    assigned = Whatsapp
                for target in node.targets:
                    if isinstance(target, ast.Name) and assigned is not None:
                        bindings[target.id] = assigned
            self.generic_visit(node)

        def visit_With(self, node):
            original = bindings.copy()
            for item in node.items:
                if isinstance(item.context_expr, ast.Call) and isinstance(
                    item.optional_vars, ast.Name
                ):
                    factory = resolve(item.context_expr.func)
                    if factory in (Create, AsyncClient):
                        bindings[item.optional_vars.id] = (
                            Whatsapp if factory is Create else AsyncClient
                        )
                    elif factory is ClientEvents.journal:
                        bindings[item.optional_vars.id] = EventJournal
            self.generic_visit(node)
            bindings.clear()
            bindings.update(original)

        visit_AsyncWith = visit_With

        def visit_Call(self, node):
            names = chain(node.func)
            known = names and (names[0] in bindings or names[:2] == ["self", "client"])
            if known:
                function = resolve(node.func)
                if function is None:
                    errors.append(f"{location}:{node.lineno}: unknown API {'.'.join(names)}")
                elif (
                    callable(function)
                    and not any(isinstance(a, ast.Starred) for a in node.args)
                    and all(k.arg for k in node.keywords)
                ):
                    try:
                        signature(function).bind(
                            *([None] * len(node.args)), **{k.arg: None for k in node.keywords}
                        )
                    except (TypeError, ValueError) as error:
                        errors.append(f"{location}:{node.lineno}: {'.'.join(names)}: {error}")
            self.generic_visit(node)

    Visitor().visit(tree)
    return errors


def verify(root=ROOT):
    errors = []
    documents = sorted(
        {
            *root.glob("*.md"),
            *root.glob("docs/*.md"),
            *root.glob("examples/*.md"),
            *root.glob("scripts/*.md"),
            *root.glob("tests/*.md"),
            *root.glob("WPP_Whatsapp/*.md"),
            *root.glob("WPP_Whatsapp/js_lib/*.md"),
        }
    )
    for path in documents:
        text = path.read_text(encoding="utf-8")
        errors += link_errors(path, text)
        for index, match in enumerate(
            re.finditer(r"^```python\s*\n(.*?)^```\s*$", text, re.M | re.S), 1
        ):
            errors += recipe_errors(match[1], f"{path.relative_to(root)} block {index}")
    for path in sorted([*root.glob("examples/*.py"), *root.glob("scripts/*.py")]):
        errors += recipe_errors(path.read_text(encoding="utf-8"), str(path.relative_to(root)))
    inventory = root / "docs/API_METHODS.md"
    if not inventory.exists() or inventory.read_text(encoding="utf-8") != generated_api():
        errors.append("docs/API_METHODS.md is stale; run python tools/verify_docs.py --write-api")
    return documents, errors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-api", action="store_true")
    args = parser.parse_args()
    if args.write_api:
        (ROOT / "docs/API_METHODS.md").write_text(generated_api(), encoding="utf-8")
    documents, errors = verify()
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    print(
        f"Validated {len(documents)} Markdown files, Python recipes/examples and generated service signatures."
    )
